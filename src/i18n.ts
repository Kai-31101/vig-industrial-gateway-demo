export const translateToChinese = (english: string) => {
  const exact = zh[english];
  if (exact) return exact;
  const demoDeveloper = english.match(/^Demo Industrial Developer (\d+)$/);
  if (demoDeveloper) return `演示工业园区开发商 ${demoDeveloper[1]}`;
  return english;
};

